// ignore_for_file: avoid_print
//
// `dart run live_activity_kit:setup`
//
// Turns a stock Flutter iOS project into one that can render Live Activities:
// creates the widget extension, wires up the App Group, patches entitlements
// and Info.plists, and registers the new target in the Xcode project.

import 'dart:io';
import 'dart:isolate';

const _defaultTargetName = 'LiveActivityKitWidget';
const _defaultDeploymentTarget = '16.1';

Future<void> main(List<String> arguments) async {
  final options = _Options.parse(arguments);
  if (options.help) {
    print(_usage);
    return;
  }

  if (!Platform.isMacOS) {
    _error('iOS setup has to run on macOS — it needs PlistBuddy and Xcode.');
    exitCode = 1;
    return;
  }

  final projectRoot = _findProjectRoot(Directory.current);
  if (projectRoot == null) {
    _error('No pubspec.yaml found. Run this from your Flutter app directory.');
    exitCode = 1;
    return;
  }

  final iosDir = Directory('${projectRoot.path}/ios');
  final xcodeproj = Directory('${iosDir.path}/Runner.xcodeproj');
  if (!xcodeproj.existsSync()) {
    _error('${xcodeproj.path} is missing. Run `flutter create --platforms=ios .` first.');
    exitCode = 1;
    return;
  }

  final packageRoot = await _packageRoot();
  if (packageRoot == null) {
    _error('Could not locate the live_activity_kit package. Is it in your dependencies?');
    exitCode = 1;
    return;
  }

  final bundleId = _bundleIdentifier(xcodeproj) ?? 'com.example.app';
  final appGroup = options.appGroup ?? 'group.$bundleId.liveactivity';
  final widgetDirName = options.targetName;
  final widgetDir = Directory('${iosDir.path}/$widgetDirName');

  _step('Flutter project', projectRoot.path);
  _step('Bundle identifier', bundleId);
  _step('App Group', appGroup);
  _step('Widget target', widgetDirName);
  print('');

  // 1. Widget extension sources -------------------------------------------
  widgetDir.createSync(recursive: true);
  final templateDir = Directory('${packageRoot.path}/templates/ios/$_defaultTargetName');
  if (!templateDir.existsSync()) {
    _error('Template directory missing at ${templateDir.path}.');
    exitCode = 1;
    return;
  }

  for (final entity in templateDir.listSync().whereType<File>()) {
    final name = _renamed(entity.uri.pathSegments.last, widgetDirName);
    final destination = File('${widgetDir.path}/$name');
    final contents = entity
        .readAsStringSync()
        .replaceAll('{{APP_GROUP}}', appGroup)
        .replaceAll(_defaultTargetName, widgetDirName);
    _writeIfSafe(destination, contents, force: options.force);
  }

  // The renderer and the attributes type are compiled into BOTH modules. They
  // are copied rather than referenced from the pod so the extension does not
  // depend on CocoaPods' output layout — and so `pod install` cannot break the
  // widget build.
  final sharedDir = Directory('${packageRoot.path}/ios/Shared');
  for (final entity in sharedDir.listSync().whereType<File>()) {
    final name = entity.uri.pathSegments.last;
    if (!name.endsWith('.swift')) continue;
    // Always overwritten: these must stay in lockstep with the Dart schema.
    File('${widgetDir.path}/$name').writeAsStringSync(
      '// Generated by `dart run live_activity_kit:setup` — do not edit.\n'
      '// Source: package:live_activity_kit/ios/Shared/$name\n\n'
      '${entity.readAsStringSync()}',
    );
    _ok('synced $name');
  }

  // 2. App entitlements ----------------------------------------------------
  final runnerEntitlements = File('${iosDir.path}/Runner/Runner.entitlements');
  if (!runnerEntitlements.existsSync()) {
    runnerEntitlements.writeAsStringSync(_emptyPlist);
    _ok('created Runner/Runner.entitlements');
  }
  _addAppGroup(runnerEntitlements, appGroup);
  _addAppGroup(File('${widgetDir.path}/$widgetDirName.entitlements'), appGroup);

  // 3. Info.plist ----------------------------------------------------------
  final runnerPlist = File('${iosDir.path}/Runner/Info.plist');
  if (!runnerPlist.existsSync()) {
    _error('${runnerPlist.path} is missing.');
    exitCode = 1;
    return;
  }
  _plistSet(runnerPlist, 'NSSupportsLiveActivities', 'bool', 'YES');
  _plistSet(runnerPlist, 'LiveActivityKitAppGroup', 'string', appGroup);
  if (options.frequentUpdates) {
    // Tells iOS the app pushes more often than the default budget allows. Only
    // set it when you really do — it costs you nothing to omit and Apple
    // reviews apps that claim it.
    _plistSet(runnerPlist, 'NSSupportsLiveActivitiesFrequentUpdates', 'bool', 'YES');
  }
  _ok('patched Runner/Info.plist');

  // 4. Xcode project -------------------------------------------------------
  if (options.skipXcode) {
    _warn('Skipped Xcode project changes (--no-xcode). Add the target manually.');
  } else {
    final result = Process.runSync(
      'ruby',
      [
        '${packageRoot.path}/tool/add_widget_target.rb',
        xcodeproj.path,
        widgetDirName,
        appGroup,
        options.deploymentTarget,
        widgetDirName,
      ],
      workingDirectory: iosDir.path,
    );
    stdout.write(result.stdout);
    if (result.exitCode != 0) {
      stderr.write(result.stderr);
      _warn('Could not update the Xcode project automatically.');
      print(_manualXcodeSteps(widgetDirName, appGroup, options.deploymentTarget));
      exitCode = 1;
      return;
    }
    _ok('registered $widgetDirName in Runner.xcodeproj');
  }

  print('');
  print(_nextSteps(appGroup, widgetDirName));
  return;
}

