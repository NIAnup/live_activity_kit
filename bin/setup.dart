String _nextSteps(String appGroup, String target) => '''
${_bold}Setup complete.$_reset Three things still need a human:

  1. ${_bold}Provisioning$_reset
     App Groups are a signing capability, so the App Group must exist on your
     Apple Developer account and be attached to BOTH bundle identifiers.
     Xcode's automatic signing does this for you the first time you build:
       open ios/Runner.xcworkspace
       select the Runner target  → Signing & Capabilities → + App Groups → $appGroup
       select the $target target → Signing & Capabilities → + App Groups → $appGroup
     A script cannot do this: it requires an authenticated Apple ID session.

  2. ${_bold}Team$_reset
     If Runner has no DEVELOPMENT_TEAM yet, set it on both targets. Live
     Activities do not run in the simulator without a signed build on iOS 16.

  3. ${_bold}Build once from Xcode$_reset
     `flutter run` builds the extension too, but the first build is where Xcode
     materialises the provisioning profiles for the new target.

Then, from Dart:

    await LiveActivity.show(
      id: 'demo',
      compact: LA.text('🍱'),
      lockScreen: LA.column([LA.text('Hello from Flutter')]),
    );
''';

String _manualXcodeSteps(String target, String appGroup, String deploymentTarget) => '''
${_bold}Manual fallback$_reset — everything except the Xcode target is already done.

  1. Xcode → File → New → Target… → Widget Extension
       Product Name: $target
       Uncheck "Include Configuration Intent"
       Check "Include Live Activity"
  2. Delete the files Xcode generates in that target.
  3. Right-click the $target group → Add Files… → select ios/$target
       ("Create groups", target membership: $target only)
  4. $target → Build Settings:
       iOS Deployment Target = $deploymentTarget
       Code Signing Entitlements = $target/$target.entitlements
  5. Both targets → Signing & Capabilities → + App Groups → $appGroup

The `xcodeproj` gem drives step 1–4 when it is available; it ships with
CocoaPods, so `sudo gem install cocoapods` (or `gem install xcodeproj`) and a
re-run of this command is usually the faster path.
''';

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

class _Options {
  _Options({
    required this.appGroup,
    required this.targetName,
    required this.deploymentTarget,
    required this.force,
    required this.skipXcode,
    required this.frequentUpdates,
    required this.help,
  });

  final String? appGroup;
  final String targetName;
  final String deploymentTarget;
  final bool force;
  final bool skipXcode;
  final bool frequentUpdates;
  final bool help;

  static _Options parse(List<String> arguments) {
    String? valueOf(String name) {
      final prefix = '--$name=';
      for (var i = 0; i < arguments.length; i++) {
        final argument = arguments[i];
        if (argument.startsWith(prefix)) return argument.substring(prefix.length);
        if (argument == '--$name' && i + 1 < arguments.length) return arguments[i + 1];
      }
      return null;
    }

    return _Options(
      appGroup: valueOf('app-group'),
      targetName: valueOf('target-name') ?? _defaultTargetName,
      deploymentTarget: valueOf('deployment-target') ?? _defaultDeploymentTarget,
      force: arguments.contains('--force'),
      skipXcode: arguments.contains('--no-xcode'),
      frequentUpdates: arguments.contains('--frequent-updates'),
      help: arguments.contains('--help') || arguments.contains('-h'),
    );
  }
}

const _usage = '''
Usage: dart run live_activity_kit:setup [options]

  --app-group=<id>           App Group identifier
                             (default: group.<bundle id>.liveactivity)
  --target-name=<name>       Widget extension target name
                             (default: $_defaultTargetName)
  --deployment-target=<v>    iOS deployment target for the extension
                             (default: $_defaultDeploymentTarget)
  --frequent-updates         Declare NSSupportsLiveActivitiesFrequentUpdates
  --force                    Overwrite widget sources you have edited
  --no-xcode                 Write files but leave Runner.xcodeproj alone
  -h, --help                 Show this message
''';

Directory? _findProjectRoot(Directory start) {
  var directory = start.absolute;
  while (true) {
    if (File('${directory.path}/pubspec.yaml').existsSync()) return directory;
    final parent = directory.parent;
    if (parent.path == directory.path) return null;
    directory = parent;
  }
}

/// Resolves this package's own directory, whether it came from pub-cache, a
/// path dependency, or a git dependency.
Future<Directory?> _packageRoot() async {
  final uri = await Isolate.resolvePackageUri(
    Uri.parse('package:live_activity_kit/live_activity_kit.dart'),
  );
  if (uri == null) return null;
  // .../live_activity_kit/lib/live_activity_kit.dart -> .../live_activity_kit
  return Directory.fromUri(uri.resolve('../'));
}

String? _bundleIdentifier(Directory xcodeproj) {
  final pbxproj = File('${xcodeproj.path}/project.pbxproj');
  if (!pbxproj.existsSync()) return null;
  final match = RegExp(r'PRODUCT_BUNDLE_IDENTIFIER = ([^;]+);')
      .allMatches(pbxproj.readAsStringSync())
      .map((m) => m.group(1)!.trim().replaceAll('"', ''))
      .where((id) => !id.endsWith('.RunnerTests') && !id.contains(r'$('))
      .toList();
  return match.isEmpty ? null : match.first;
}

String _renamed(String fileName, String targetName) =>
    fileName.replaceAll(_defaultTargetName, targetName);

/// Never clobbers developer edits: a file that differs from what we last wrote
/// is left alone unless `--force` is passed.
void _writeIfSafe(File file, String contents, {required bool force}) {
  final name = file.uri.pathSegments.last;
  if (file.existsSync() && !force) {
    if (file.readAsStringSync() == contents) {
      _ok('$name up to date');
    } else {
      _warn('$name exists and differs — left untouched (pass --force to replace)');
    }
    return;
  }
  file.writeAsStringSync(contents);
  _ok('wrote $name');
}

void _addAppGroup(File entitlements, String appGroup) {
  if (!entitlements.existsSync()) {
    entitlements.writeAsStringSync(_emptyPlist);
  }
  const key = 'com.apple.security.application-groups';
  final existing = _plistRead(entitlements, key);
  if (existing == null) {
    _plistBuddy(entitlements, ['-c', 'Add :$key array']);
  }
  if (existing == null || !existing.contains(appGroup)) {
    _plistBuddy(entitlements, ['-c', 'Add :$key: string $appGroup']);
    _ok('added $appGroup to ${entitlements.uri.pathSegments.last}');
  } else {
    _ok('${entitlements.uri.pathSegments.last} already has the App Group');
  }
}

void _plistSet(File plist, String key, String type, String value) {
  final result = _plistBuddy(plist, ['-c', 'Set :$key $value']);
  if (result.exitCode != 0) {
    _plistBuddy(plist, ['-c', 'Add :$key $type $value']);
  }
}

String? _plistRead(File plist, String key) {
  final result = _plistBuddy(plist, ['-c', 'Print :$key']);
  return result.exitCode == 0 ? result.stdout.toString() : null;
}

ProcessResult _plistBuddy(File plist, List<String> arguments) => Process.runSync(
      '/usr/libexec/PlistBuddy',
      [...arguments, plist.path],
    );

const _emptyPlist = '''
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
</dict>
</plist>
''';

const _bold = '[1m';
const _reset = '[0m';

void _step(String label, String value) => print('  $label: $value');
void _ok(String message) => print('  [32m✓[0m $message');
void _warn(String message) => print('  [33m![0m $message');
void _error(String message) => stderr.writeln('[31m✗[0m $message');
